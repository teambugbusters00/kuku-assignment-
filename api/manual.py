"""Deterministic local baselines used when AI providers are unavailable."""
from __future__ import annotations

import re
from collections import Counter

from api.rag import retrieve_top_k


def ps1_baseline(text: str, title: str, language: str) -> dict:
    sentences = [s.strip() for s in re.split(r"(?<=[.!?])\s+", text) if s.strip()]
    words = re.findall(r"[A-Za-z][A-Za-z'-]{2,}", text.lower())
    counts = Counter(words)
    keywords = [word for word, _ in counts.most_common(12)]
    cues = {
        "Romance": ("love", "kiss", "relationship", "marry", "husband", "wife"),
        "Mystery": ("mystery", "secret", "clue", "strange", "hidden", "disappear"),
        "Crime": ("murder", "police", "detective", "crime", "suspect", "weapon"),
        "Drama": ("family", "father", "mother", "betray", "argument", "promise"),
        "Fantasy": ("magic", "kingdom", "spell", "dragon", "wizard"),
        "Science Fiction": ("space", "robot", "alien", "planet", "satellite"),
        "Horror": ("ghost", "haunted", "fear", "blood", "demon", "darkness"),
    }
    genres = [genre for genre, terms in cues.items() if any(term in words for term in terms)]
    summary = " ".join(sentences[:3])[:700]
    return {
        "title": title,
        "summary": summary,
        "genre": genres or ["Unclassified"],
        "tags": keywords[:10],
        "themes": [],
        "characters": [],
        "emotions": [],
        "content_warnings": [],
        "language": language,
        "confidence": 0.35,
        "evidence_notes": ["Generated by deterministic local keyword and sentence rules."],
        "provider": "Local baseline",
        "model": "rules-v1",
        "analysis_mode": "baseline",
    }


def ps2_baseline(profile: str, catalog: str, top_n: int) -> dict:
    entries = [line.strip() for line in catalog.splitlines() if line.strip()]
    profile_terms = set(re.findall(r"[a-z0-9]{3,}", profile.lower()))
    scored = []
    for index, line in enumerate(entries):
        terms = set(re.findall(r"[a-z0-9]{3,}", line.lower()))
        overlap = len(profile_terms & terms)
        score = round(100 * overlap / max(1, len(profile_terms)))
        title_match = re.search(r"title\s*:\s*([^|]+)", line, re.I)
        id_match = re.search(r"(?:id|catalog(?:_reference)?)\s*:\s*([^|]+)", line, re.I)
        scored.append((overlap, index, {
            "rank": 0,
            "title": title_match.group(1).strip() if title_match else f"Catalog item {index + 1}",
            "id_or_catalog_reference": id_match.group(1).strip() if id_match else str(index + 1),
            "match_score": min(score, 100),
            "reasons": ["Keyword overlap with listener profile"],
            "why_this_fits": "Ranked by lexical overlap between the profile and this catalog entry.",
            "content_notes": [],
        }))
    selected = sorted(scored, key=lambda item: (-item[0], item[1]))[:top_n]
    recs = [item[2] for item in selected]
    for rank, item in enumerate(recs, 1):
        item["rank"] = rank
    return {
        "recommendations": recs,
        "profile_signals": sorted(profile_terms)[:12],
        "diversity_note": "Local lexical baseline; recommendation quality depends on catalog metadata.",
        "provider": "Local baseline",
        "model": "keyword-ranker-v1",
        "analysis_mode": "baseline",
    }
